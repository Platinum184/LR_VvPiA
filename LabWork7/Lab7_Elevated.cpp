// Подключаем библиотеки для работы с вводом/выводом.
#include <iostream>   // Для базовых операций ввода/вывода.
#include <iomanip>   // Для форматированного вывода.
#include <cstdlib>   // Для генерации случайных чисел.
#include <ctime>   // Для работы со временем.

// Подключаем стандартное пространство имён.
using namespace std;

int main()   // Главная функция программы.
{
    // Объявляем константу для размера матрицы.
    const int N = 5;   // Размер квадратной матрицы (N×N).

    // Создаём двумерный массив для хранения матрицы.
    int matrix[N][N];   // Объявление матрицы.

    // Инициализируем генератор случайных чисел.
    srand(static_cast<unsigned>(time(nullptr)));   // Используем текущее время как seed.

    // Заполняем матрицу случайными числами.
    for (int i = 0; i < N; i++) {   // Цикл по строкам.
        for (int j = 0; j < N; j++) {   // Цикл по столбцам.
            matrix[i][j] = rand() % 100;   // Генерируем числа от 0 до 99.
        }
    }

    // Выводим исходную матрицу.
    cout << "Original matrix:\n";   // Заголовок.
    for (int i = 0; i < N; i++) {   // Цикл по строкам.
        for (int j = 0; j < N; j++) {   // Цикл по столбцам.
            cout << setw(4) << matrix[i][j];   // Форматированный вывод с шириной поля 4.
        }
        cout << endl;   // Переход на новую строку после каждой строки матрицы.
    }

    // Выполняем транспонирование матрицы на месте.
    // Важно: проходим только по элементам выше главной диагонали.
    for (int i = 0; i < N; i++) {   // Внешний цикл по строкам.
        for (int j = i + 1; j < N; j++) {   // Внутренний цикл по столбцам (начинаем с i+1).
            // Меняем местами элементы.
            int temp = matrix[i][j];   // Сохраняем значение в временную переменную.
            matrix[i][j] = matrix[j][i];   // Присваиваем значение из симметричного элемента.
            matrix[j][i] = temp;   // Восстанавливаем сохранённое значение.
        }
    }

    // Выводим транспонированную матрицу.
    cout << "\nTransposed matrix:\n";   // Заголовок.
    for (int i = 0; i < N; i++) {   // Цикл по строкам.
        for (int j = 0; j < N; j++) {   // Цикл по столбцам.
            cout << setw(4) << matrix[i][j];   // Форматированный вывод.
        }
        cout << endl;   // Переход на новую строку.
    }

    return 0;   // Успешное завершение программы.
}
