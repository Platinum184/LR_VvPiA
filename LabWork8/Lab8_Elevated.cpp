#include <iostream> // Библиотека для ввода и вывода.
#include <string> // Библиотека для работы со строками.
#include <sstream> // Проверка пробельных символов.
#include <vector> // Хранение слов в масстве.

using namespace std; // Подключаем стандартное пространство имён.

int main() // Объявляем главную функцию.
{
	string line; // Переменная для исходной строки.

	cout << "Enter the line: "; // Просим пользователя ввести строку.

	getline(cin, line); // Считываем строку.

	// Проверяем не пустая ли строка.
	if (line.empty()) {
		cout << "The line is empty!" << endl;
		return 0;
	}

	istringstream input(line);	// Создаём поток для разделения строки на слова.

	vector<string> words;	// Вектор для хранения всех слов.

	string word; // Переменная для временного хранения слова.

	// ПЕРВЫЙ ПРОХОД :
	// Считываем все слова из исходной строки.
	while (input >> word) {
		words.push_back(word); // Добавляем каждое слово в вектор.
	}

	string result; // Строка для хранения результата.

	// ВТОРОЙ ПРОХОД:
	// Перебираем слова в обратном порядке.
	for (int i = static_cast<int>(words.size()) - 1;
		i >= 0; i--) {

		// Если результат уже содержит слово, добавляем между словами пробел.
		if (!result.empty()) {
			result += " ";
		}

		// Добавляем очередное слово.
		result += words[i];
	}

	// Выводим результат.
	cout << "Result: " << result << endl;

	return 0; // Успешное завершение программы.
}