#include <iostream> // Библиотека для ввода и вывода.
#include <string> // Библиотека для работы со строками.
#include <cctype> // Проверка пробельных символов.

using namespace std; // Подключаем стандартное пространство имён.

int main() // Объявляем главную функцию.
{
	string line; // Создаём переменную для хранения строки.

	cout << "Enter the line: "; // Просим пользователя ввести строку.

	getline(cin, line); // Считываем всю строку, включая пробелы.

	int wordCount = 0; // Счётчик слов.

	bool inWord = false; // Флаг: находимся ли мы внутри слова.

	// Проходим по кадому символу строки.
	for (char c : line) {

		// Проверяем, является ли символ пробельным.
		if (isspace(static_cast<unsigned char>(c))) {
			inWord = false; // Если встрели пробел, значит текущее слово закончилось.
		}

		else {
			// Если символ не пробел и мы ещё не находимся внутри слова.
			if (!inWord) {
				wordCount++; // Началось новое слово.
				inWord = true; //Отмечаем, что теперь мы внутри слова.
			}
		}
	}

	// Вывод результата.
	cout << "Number of words: " << wordCount << endl; 

	return 0; // Успешное завершение программы.
}