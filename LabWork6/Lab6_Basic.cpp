#include <iostream> // Подключаем библиотеку для ввода/вывода.
#include <iomanip> // Подключаем библиотеку для управления форматированием ввода/вывода.

using namespace std; // Подключаем стандартное пространство имён.

int main() // Объявляем главную функцию.
{
	const int SIZE = 5; // Размер статического массива.
	// Используем const, поскольку размер массива должен быть известен на этапе компиляции.
	
	int arr[SIZE]; // Объявляем статический массив состоящий из 5 целых чисел.

	int sum = 0; // Переменная для храниения суммы элементов.
	double AverageValue = 0; // Переменная для хранения среднего значения.

	// Заполенение массива с клавиатуры.
	cout << "Enter " << SIZE << " integers: " << endl;
	// Цикл проходит по всем индексам массива.
	for (int i = 0; i < SIZE; i++) {
		cout << "arr[" << i << "] = ";
		cin >> arr[i]; // Считываем число и записываем его в соответствующую ячейку.
	}

	// Проверяем, правильно ли пользователь ввёл число.
	if (cin.fail()) {
		cout << "ERROR!! It is necessary to enter an integer!" << endl;
		return 1;
	}

	// Вывод массива.
	cout << "\nInitial array: " << endl;
	// Выводим каждый элемент масива.
	for (int i = 0; i < SIZE; i++) {
		cout << setw(6) << arr[i];
	}
	cout << endl;

	// Вычисление суммы элементов.
	// Перебираем каждый элемент массива и прибавляем каждый элемент к переменной sum.
	for (int i = 0; i < SIZE; i++) {
		sum += arr[i];
	}

	// Вычисление среднего арифметического.
	// Преобразовываем сумму в double, чтобы получить вещественное деление.
	AverageValue = static_cast<double>(sum) / SIZE;

	// Вывод результатов.
	cout << "\n=== Results ===" << endl;

	// Выводим сумму элементов массива.
	cout << "The sum of the elements: " << sum << endl; 

	// Выводим среднее арифметическое с двумя знаками после запятой.
	cout << fixed << setprecision(2);
	cout << "Arithmetic mean: " << AverageValue << endl;

	return 0; // Завершаем программу успешно.
}
