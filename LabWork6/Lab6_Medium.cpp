#include <iostream> // Подключаем библиотеку для ввода/вывода.
#include <iomanip> // Подключаем библиотеку для управления форматированием ввода/вывода.
#include <random> // Генератор случайных чисел.

using namespace std; // Подключаем стандартное пространство имён.

int main() // Объявляем главную функцию.
{
	// Объявление массива и переменных.

	const int SIZE = 20; // Размер статического массива.
	// Используем const, поскольку размер массива должен быть известен на этапе компиляции.
	// Размер согласно заданию.

	//Границы диапазона случайных чисел.
	// Диапазон согласно заданию.
	const int min_random = -50;
	const int max_random = 50;

	// Объявляем статический массив.
	int arr[SIZE];

	// Переменные для обработки массива.
	int sumPositive = 0;  // Сумма положительных чисел.
	int sumNegative = 0;  // Сумма отрицательных чисел.
	int sumTotal = 0;  // Общая сумма элементов массива.

	// Счётчики положительных и отрицательных элементов.
	int PositiveCount = 0;
	int NegativeCount = 0;

	// Переменные для поиска минимума и максимума.
	int MinValue;
	int MaxValue;

	// Переменная для среднего арифметического.
	double AverageValue = 0;

	// Создание генератора случайных чисел.

	random_device rd; // Получает начальное значение генератора.
	mt19937 gen(rd()); // Генератор псевдослучайных чисел.
	// Задаём равномерное распределение целых чисел от -50 до 50 включительно.
	uniform_int_distribution<int> distribution(min_random, max_random);

	// Заполнение массива.
	cout << "Generation of an array from " << SIZE << " elements." << endl;

	// Заполняем каждую ячейку массива.
	for (int i = 0; i < SIZE; i++) {
		// Получаем случайное число и записываем его в массив.
		arr[i] = distribution(gen);
	}

	// Вывод исходного массива.
	cout << "\nInitial array: " << endl;

	// Выводим каждый элемент масива.
	for (int i = 0; i < SIZE; i++) {
		cout << setw(6) << arr[i];
		// После каждых 10 элементов начинаем новую строку.
		if ((i + 1) % 10 == 0) {
			cout << endl;
		}
	}

	// Инициализация минимума и максимума.
	// Принимаем первый эленет массива за начальные значения максимума и минимума.

	MinValue = arr[0];
	MaxValue = arr[0];

	// Компелксная обработка массива.

	// Перебираем все элементы массива.
	for (int i = 0; i < SIZE; i++) {
		sumTotal += arr[i];

		// Проверяем, является ли элемент положительным.
		if (arr[i] > 0) {
			// Добавляем положительный элемент к сумме положительных чисел.
			sumPositive += arr[i];
			// Увеличиваем количество положительных элементов.
			PositiveCount++;
		}

		// Проверяем, является ли элемент отрицательным.
		else if (arr[i] < 0) {

			// Добавляем отрицательный элемент к сумме отрицательных чисел.
			sumNegative += arr[i];

			// Увеличиваем количество отрицательных элементов.
			NegativeCount++;
		}
		// Нули не входят ни в положительные, ни в отрицательные элементы.

		// Ищем минимальный элемент.
		if (arr[i] < MinValue) {
			MinValue = arr[i];
		}

		// Ищем максимальный элемент.
		if (arr[i] > MaxValue) {
			MaxValue = arr[i];
		}
	}

	// Вычисление среднего арифметического.
	// Используем вещественное деление, чтобы сохранить дробную часть результата.
	AverageValue = static_cast<double>(sumTotal) / SIZE;

	// Вывод результатов.
	cout << fixed << setprecision(2);

	cout << "\n=== Results ===" << endl;

	// Выводим сумму положительных элементов.
	cout << "\nThe sum of positive elements: " << sumPositive << endl;

	// Выводим сумму отрицательных элементов.
	cout << "The sum of negative elements: " << sumNegative << endl;

	// Дополнительные результаты обработки массива.

	// Выводим общую сумму .
	cout << "\nThe total sum of the elements: " << sumTotal << endl;

	// Выводим среднее арифметическое.
	cout << "Arithmetic mean: " << AverageValue << endl;

	// Выводим минимальный элемент.
	cout << "Minimum element: " << MinValue << endl;

	// Выводим сумму максимальный элемент.
	cout << "Maximum element: " << MaxValue << endl;

	// Выводим количество отрицательных элементов.
	cout << "The number of positive elements: " << PositiveCount << endl;

	// Выводим количество положительных элементов.
	cout << "The number of negative elements: " << NegativeCount << endl;

	return 0; // Завершаем программу успешно.
}
