#include <iostream> // Подключаем библиотеку для ввода/вывода.
#include <iomanip> // Подключаем библиотеку для управления форматированием ввода/вывода.
#include <cmath>    // Подключаем библиотеку для математической функции cos().

using namespace std; // Подключаем стандартное пространство имён.

int main() // Объявляем главную функцию.
{
	const int WIDTH = 10; // Константа - ширина столбца таблицы.
	const double EPS = 1e-9; // Константа - допуск на погрешность типа double.

	double a; // Переменная для хранения a - начало интервала.
	double b; // Переменная для хранения b - конца интервала.
	double h; // Переменная для хранения h - шаг.

	// Запрашиваем ввод у пользователя.
	cout << "Tabulating the function y = cos(x)" << endl;

	cout << "Enter the beginning of the interval a: ";
	cin >> a; // Считываем введённое значение в переменную a.

	// Проверяем, что пользователь ввёл именно числа, а не буквы.
	if (cin.fail()) {
		cout << "ERROR: incorrect input!" << endl;
		return 1; // Завершаем программу с кодом ошибки.
	}

	cout << "Enter the end of interval b: ";
	cin >> b; // Считываем введённое значение в переменную b.

	// Проверяем, что пользователь ввёл именно числа, а не буквы.
	if (cin.fail()) {
		cout << "ERROR: incorrect input!" << endl;
		return 1; // Завершаем программу с кодом ошибки.
	}

	cout << "Enter step h: ";
	cin >> h; // Считываем введённое значение в переменную h.

	// Проверяем, что пользователь ввёл именно числа, а не буквы.
	if (cin.fail()) {
		cout << "ERROR: incorrect input!" << endl;
		return 1; // Завершаем программу с кодом ошибки.
	}

	// Проверка корректности ввода.
	if (a > b) // Начало не должно быть больше конца, иначе цикл не выполнится ни разу.
	{
		cout << "ERROR: the beginning of the interval cannot be greater than the end!" << endl;
		return 1;
	}
	if (h <= 0) // Шаг должен быть положительным.
	{
		cout << "ERROR: the step must be positive!" << endl;
		return 1;
	}

	// Инициализируем min и max значением функции в ПЕРВОЙ точке (а не нулём!):
	// если начать с 0, для строго положительной функции минимум будет найден неверно,
	// а для cos(x) значения вообще могут не включать 0 на данном интервале.
	double MinY = cos(a); // Текущий минимум значений функции.
	double MaxY = cos(a); // Текущий максимум значений функции.
	double MinX = a; // Аргумент, в котором достигнут минимум.
	double MaxX = a; // Аргумент, в котором достигнут максимум.

	// Шапка таблицы.
	cout << "\n+----------+----------+" << endl;
	cout << "|    x     |  cos(x)  |" << endl;
	cout << "+----------+----------+" << endl;

	// Форматирование вывода: 4 знака после запятой.
	cout << fixed << setprecision(4);

	// Цикл табуляции.
	// Цикл for выбран потому, что количество итераций известно заранее:
	// оно определяется длиной интервала (b - a) и шагом h.
	// 1) double x = a — начинаем с начала интервала;
	// 2) x <= b + EPS — условие продолжения; EPS компенсирует погрешность double;
	// 3) x += h — сдвигаемся к следующей точке.

	for (double x = a; x <= b + EPS; x += h) {
		// Вычисляем значение функции в текущей точке.
		// cos(x) определена на всей числовой оси, поэтому особых точек,
		// требующих пропуска, у этой функции нет.
		double y = cos(x);

		// Выводим строку таблицы: setw(WIDTH) выравнивает оба столбца.
		cout << "|" << setw(WIDTH) << x
			<< "|" << setw(WIDTH) << y << "|" << endl;

		// Обновление минимума.
		// Если текущее значение меньше найденного ранее — запоминаем его и аргумент.
		if (y < MinY) {
			MinY = y;
			MinX = x;
		}
		// Обновление максимума.
		// Если текущее значение больше найденного ранее — запоминаем его и аргумент.
		if (y > MaxY) {
			MaxY = y;
			MaxX = x;
		}
	}

	// Нижняя граница таблицы.
	cout << "+----------+----------+" << endl;

	// Вывод результатов поиска.
	// min и max функции на интервале.
	cout << "\nSearch results:" << endl;
	cout << "Minimum: cos(" << setw(WIDTH) << MinX << ") = " << setw(WIDTH) << MinY << endl;
	cout << "Maximum: cos(" << setw(WIDTH) << MaxX << ") = " << setw(WIDTH) << MaxY << endl;

	return 0; // Успешное завершение программы.
}
