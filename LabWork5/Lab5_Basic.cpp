#include <iostream> // Подключаем библиотеку для ввода/вывода.
#include <iomanip> // Подключаем библиотеку для управления форматированием ввода/вывода.

using namespace std; // Подключаем стандартное пространство имён.

int main() // Объявляем главную функцию.
{
	const int WIDTH = 12; // Константа - ширина столбца таблицы.
	const double EPS = 1e-9; // Константа - допуск на погрешность типа double.

	double a; // Переменная для хранения a - начало интервала.
	double b; // Переменная для хранения b - конца интервала.
	double h; // Переменная для хранения h - шаг.

	// Запрашиваем ввод у пользователя.
	cout << "Tabulating the function y = x^2 - 2*x + 1" << endl;
	cout << "Enter the beginning of the interval a: ";
	cin >> a; // Считываем введённое значение в переменную a.

	// Проверяем, что пользователь ввёл именно числа, а не буквы.
	if (cin.fail()) {
		cout << "ERROR: incorrect input!" << endl;
		return 1; // Завершаем программу с кодом ошибки.
	}

	cout << "Enter the end of interval b: ";
	cin >> b; // Считываем введённое значение в переменную b.

	// Проверяем, что пользователь ввёл именно числа, а не буквы.
	if (cin.fail()) {
		cout << "ERROR: incorrect input!" << endl;
		return 1; // Завершаем программу с кодом ошибки.
	}

	cout << "Enter step h: ";
	cin >> h; // Считываем введённое значение в переменную h.

	// Проверяем, что пользователь ввёл именно числа, а не буквы.
	if (cin.fail()) {
		cout << "ERROR: incorrect input!" << endl;
		return 1; // Завершаем программу с кодом ошибки.
	}

	// Проверка корректности ввода.
	if (a > b) // Начало не должно быть больше конца, иначе цикл не выполнится ни разу.
	{
		cout << "ERROR: the beginning of the interval cannot be greater than the end!" << endl;
		return 1;
	}
	if (h <= 0) // Шаг должен быть положительным.
	{
		cout << "ERROR: the step must be positive!" << endl;
		return 1;
	}

	// Шапка таблицы.
	cout << "\n+------------+------------+" << endl;
	cout << "|      x     |  y = f(x)  |" << endl;
	cout << "+------------+------------+" << endl;

	// Форматирование вывода: 4 знака после запятой.
	cout << fixed << setprecision(4);

	// Цикл табуляции.
	// Цикл for выбран, потому что количество итераций заранее известно: оно зависит от длины интервала и шага.
	// Для сравнения double используется не x <= b, а x <= b + 1e-9:
	// из-за накопления погрешности при x += h последняя точка может получиться чуть меньше b, и прямое сравнение её бы пропустило.
	for (double x = a; x <= b + EPS; x += h) {
		double y = x * x - 2.0 * x + 1.0; // Значение функции в точке x.

		// setw(12) — выравнивание столбцов по ширине 12 (константа WIDTH) символов.
		std::cout << "|" << std::setw(WIDTH) << x
			<< "|" << std::setw(WIDTH) << y << "|" << std::endl;
	}

	// Нижняя граница таблицы.
	std::cout << "+------------+------------+" << std::endl;

	return 0; // Завершаем программу успешно.
}